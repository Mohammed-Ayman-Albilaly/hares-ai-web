import { z } from 'zod';
import {
  CATEGORY_CODES,
  CategoryCodeSchema,
  ClassificationSourceSchema,
  LogActionSchema,
  PlatformSchema,
  RiskLevelSchema,
  SchemaVersionSchema,
  UserDecisionSchema,
} from './enums';

/**
 * Log ingestion contract (ARCHITECTURE.md §7(c), §5.a; WEB-FR-045–049, WEB-FR-056;
 * WEB-NFR-002/005/008/011/021; DECISIONS #2). All JSON fields are snake_case.
 *
 *   POST /logs (Bearer token, allowlisted event)
 *     -> 201 accepted   (new row)
 *     -> 200 idempotent ack (duplicate log_id; no new row)
 *
 * Strict allowlist: unknown fields (including user_id / department_id and any
 * prompt-text field) are rejected with HTTP 400 and nothing is stored.
 * `user_id` and `department_id` are derived server-side from the access token and
 * the live user record — they are never accepted from the payload.
 * `log_id` (UUID, generated by the extension) is the idempotency key.
 * Enum values are gated by `schema_version`; unknown values -> 400 with accepted values.
 */

/** A single activity-log event as posted by the extension (Section 6 allowlist). */
export const LogEventSchema = z
  .object({
    log_id: z.string().uuid(),
    event_time: z.string().datetime(),
    platform: PlatformSchema,
    risk_level: RiskLevelSchema,
    action: LogActionSchema,
    // Category codes as matched by the extension. May be empty (NONE risk); no
    // duplicates; at most one per category (there are 24 category codes).
    categories: z
      .array(CategoryCodeSchema)
      .max(CATEGORY_CODES.length)
      .refine((arr) => new Set(arr).size === arr.length, {
        message: 'categories must not contain duplicates',
      }),
    classification_source: ClassificationSourceSchema,
    user_decision: UserDecisionSchema,
    rule_id: z.string().nullable().optional(),
    schema_version: SchemaVersionSchema,
  })
  .strict();
export type LogEvent = z.infer<typeof LogEventSchema>;

/** Acknowledgement body for both 201 (accepted) and 200 (duplicate). */
export const LogIngestionResponseSchema = z.object({
  log_id: z.string().uuid(),
});
export type LogIngestionResponse = z.infer<typeof LogIngestionResponseSchema>;
